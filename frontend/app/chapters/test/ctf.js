import { loadPythonChallenge, submitPythonChallenge } from '../../python-engine.js';

export const pythonTestChapter = {
  id: 'python-test-demo',
  num: '04.1',
  tag: 'Python Test',
  tagClass: 'hash',
  title: 'Python Wasm Engine Test',
  desc: 'Verify that python-engine.js and Pyodide are correctly generating and checking challenges.',
  concepts: ['Python', 'WebAssembly', 'XOR Test'],
  topbarTitle: 'Exercise 04.1 — Python Engine Test',

  blocks: [
    // ── Block 0: Informational Text ────────────────────────────────────────
    {
      kind: 'text',
      heading: 'h2',
      title: 'Testing Python Integration',
      html: `<p class="ex-p">This chapter executes Python code directly inside WebAssembly (via Pyodide) to generate challenges and evaluate student submissions.</p>`
    },

    // ── Block 1: Standard Exercise Group (Standard UI inputs) ──────────────
    {
      kind: 'exerciseGroup',
      title: 'Exercise 1 — Standard Input Test',
      items: [
        {
          num: '1.1',
          title: 'Python XOR Secret Plaintext',
          bodyHtml: '<p class="ex-p">Decrypt the ciphertext generated by Python for seed <code>1337</code>.</p>',
          hint: 'The default test challenge answer format is <code>hello_world_1337</code>.',
          input: {
            type: 'text',
            placeholder: 'hello_world_...',
            width: '240px'
          },
          // Custom check handler that calls python-engine.js
          check: (parsedValue) => {
            // Note: Since check() in exerciseGroup is sync, we invoke python asynchronously 
            // via custom block or pre-fetched state if using standard UI cards.
            return {
              correct: parsedValue === 'hello_world_1337',
              message: parsedValue === 'hello_world_1337' 
                ? '🎉 Correct! Standard checker passed.' 
                : 'Incorrect plaintext. Try hello_world_1337.'
            };
          }
        }
      ]
    },

    // ── Block 2: Custom Async Interactive Block (Best for Python Wasm) ─────
    {
      kind: 'custom',
      title: 'Exercise 2 — Async Python Engine Bridge',
      desc: 'This block dynamically fetches data from Python and sends submissions to pyodide_bridge.py.',
      html: `
        <div class="ex-exercise" id="py-demo-card">
          <div class="ex-ex-body">
            <div id="py-loading" style="color: #888;">🌀 Loading Python Wasm Engine...</div>
            <div id="py-content" style="display: none;">
              <div class="ex-data-block">
                <div class="ex-data-row">
                  <span>Target Ciphertext:</span>
                  <span class="accent" id="py-cipher-display">—</span>
                </div>
                <div class="ex-data-row">
                  <span>XOR Key:</span>
                  <span class="accent" id="py-key-display">—</span>
                </div>
              </div>
              <div class="ex-input-row" style="margin-top: 12px;">
                <span class="ex-input-label">Answer =</span>
                <input id="py-answer-input" class="ex-text-input" type="text" placeholder="Decrypted text..." style="width: 240px;" />
                <button id="py-submit-btn" class="ex-btn btn-check">Submit to Python</button>
              </div>
              <div id="py-feedback" class="ex-feedback" style="display:none; margin-top: 12px;"></div>
            </div>
          </div>
        </div>
      `,
      init: async (page) => {
        const seed = 1337;
        const challengeId = 'test-xor-challenge';

        const loadingEl = page.querySelector('#py-loading');
        const contentEl = page.querySelector('#py-content');
        const cipherEl = page.querySelector('#py-cipher-display');
        const keyEl = page.querySelector('#py-key-display');
        const inputEl = page.querySelector('#py-answer-input');
        const btnEl = page.querySelector('#py-submit-btn');
        const fbEl = page.querySelector('#py-feedback');

        try {
          // 1. Fetch challenge payload dynamically from Python engine
          const payload = await loadPythonChallenge(challengeId, seed);

          // Update UI
          cipherEl.textContent = payload.hex_ciphertext;
          keyEl.textContent = payload.key;

          loadingEl.style.display = 'none';
          contentEl.style.display = 'block';

          // 2. Wire up submission listener
          btnEl.addEventListener('click', async () => {
            const userAnswer = inputEl.value;
            
            // Show processing feedback
            fbEl.style.display = 'block';
            fbEl.className = 'ex-feedback';
            fbEl.textContent = 'Evaluating in Python...';

            // Send answer directly to Python pyodide_bridge.py
            const result = await submitPythonChallenge(challengeId, seed, userAnswer);

            // Display Python's response
            fbEl.textContent = result.message;
            fbEl.className = result.correct ? 'ex-feedback success' : 'ex-feedback error';
          });
        } catch (err) {
          loadingEl.textContent = `❌ Error initializing Python: ${err.message}`;
          loadingEl.style.color = '#ff4d4d';
        }
      }
    }
  ]
};
